// AllFields returns NetworkFields followed by DataplaneFields in canonical extraction order.
func AllFields() []FieldSpec {
	out := make([]FieldSpec, 0, len(NetworkFields)+len(DataplaneFields))
	out = append(out, NetworkFields...)
	out = append(out, DataplaneFields...)
	return slices.Clip(out)
}
